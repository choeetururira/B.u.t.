const EMOJI_LINES = ['오늘도 최고였다 ✨', '도쿄의 밤은 반짝반짝 🌃'];

function buildVirtualSubmissions(photoNames, opts = {}) {
  const r = rng(opts.seed || 2026);
  const pick = (a) => a[Math.floor(r() * a.length)];
  const out = [];
  for (let s = 1; s <= 20; s++) {
    const studentId = String(s).padStart(2, '0');
    for (let day = 1; day <= 4; day++) {
      // 일부 학생은 일부 날짜 미제출 (현황판 검증용)
      if ((s === 19 && day === 2) || (s === 20 && day >= 3)) continue;
      const P = POOL[day];
      let essay = pick(P.essay) + (r() < 0.5 ? '\n\n' + pick(P.essay) : '');
      let reflection = pick(P.refl);
      let oneLine = pick(P.one);
      if (s === 7 && day === 1) essay = (essay + ' ').repeat(10).slice(0, 2990); // 최대 길이 경계
      if (s === 8 && day === 2) reflection = '안내판이 그림으로 되어 있어 누구나 쉽게 길을 찾았다.'; // 30자 근처
      if (s === 9) oneLine = EMOJI_LINES[day % 2];
      if (s === 10 && day === 3) oneLine = '말보다 먼저 통한 마음, 그게 바로 벗이었다'; // 30자 경계
      const nPhotos = 1 + Math.floor(r() * 3);
      const dayPhotos = photoNames.filter((n) => n.startsWith('day' + day + '_') && !n.includes('_big'));
      const photos = [];
      for (let k = 0; k < nPhotos; k++) photos.push(dayPhotos[(s * 3 + k * 7 + day) % dayPhotos.length]);
      if (s === 3) photos[0] = 'day' + day + '_99_big.jpg'; // 휴대폰 원본 크기
      out.push({
        studentId, day, reflection, essay, oneLine,
        photos: photos.map((f, k) => ({ file: f, caption: k === 0 ? '미션 ' + (k + 1) + ' 기록' : '', mission: k === 0 ? '1' : k === 1 ? '2' : '' }))
      });
    }
  }
  return out;
}

module.exports = { buildVirtualSubmissions, POOL };
